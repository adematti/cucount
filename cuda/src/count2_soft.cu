// ============================================================================
// Per-pair soft scatter
// ============================================================================
//
// The taps are a truncated Gaussian centred on the peak bin, generated by
// multiplicative recurrence rather than a table or a call to exp per tap:
//
//   R_t = w_{c+t} / w_{c+t-1} = exp((2u_t - ds) * ds / (2 sigma^2))
//
// and, because the logits x_i are quadratic in i, successive ratios differ by
// the constant factor exp(-gg). So the whole window costs two exp() calls (one
// per direction) and one multiply per tap. This is pyfcfc's recurrence, kept
// rather than a LUT because it is both exact and memory-free.
//
// Two passes over the window: the first sums the (unnormalized) taps so the
// second can divide by it. Renormalizing is what keeps a pair's total weight
// equal to w_pair -- the sum over bins is the same number the hard kernel would
// have added, just spread out -- and, at the array edge, what absorbs the taps
// that fall outside [0, nbins). The passes are pure arithmetic apart from the
// atomics in the second, so the extra pass costs ~2 flops per tap.

// A scatter target is either the shared block tile (atomic) or a thread-private
// row of it, in which case no other thread can touch the slot and a plain add is
// both correct and far cheaper.
template <bool ATOMIC>
__device__ __forceinline__ void soft_increment(FLOAT *p, FLOAT v)
{
    if constexpr (ATOMIC) {
        atomicAdd(p, v);
    }
    else {
        *p += v;
    }
}


// `stride` is the histogram stride between neighbouring s bins: 1 for a plain
// soft-s request, nell when the multipoles are folded into `hist` (see
// soft_add_pole below, which calls this once per multipole on hist + ill).
template <bool ATOMIC>
__device__ __forceinline__ void soft_add_uniform(
    FLOAT *hist,
    const SoftBinSpec &sp,
    FLOAT s,
    FLOAT w,
    const int stride)
{
    // Same rule as the hard kernel's range check: a pair outside the binning is
    // dropped whole, not clipped into the first/last bin. NaN falls out here.
    if (!(s >= sp.lo) || !(s < sp.hi)) {
        return;
    }

    int m = (int) floor((s - sp.c0) * sp.inv_ds + 0.5);

    if (m < 0) {
        m = 0;
    }
    else if (m >= sp.nbins) {
        m = sp.nbins - 1;
    }

    const FLOAT u = s - (sp.c0 + m * sp.ds);

    // log of w_{m+1}/w_m and of w_{m-1}/w_m. Only one exponential is needed:
    // rdn = exp(-md) * exp(-gg) = iq / rup, since exp(-md) = 1 / exp(md). The
    // division is a few cycles, a second double exp() is not; the fallback only
    // triggers for sigma far below the bin width, where exp(md) underflows.
    const FLOAT md = (2 * u - sp.ds) * sp.ds * sp.inv2sig2;
    const FLOAT rup = exp(md);
    const FLOAT rdn = (rup > 0) ? sp.iq / rup : exp(-md - sp.gg);
    const int kmax = sp.kmax;

    // Fast path: when the whole window is interior, no tap can leave [0, nbins)
    // and every tap inside kmax is above the cutoff by construction, so the two
    // loops become branch-free arithmetic. This is the overwhelmingly common
    // case for a binning that is not tiny.
    if (m >= kmax && m + kmax < sp.nbins) {
        // Interior: no tap can leave [0, nbins) and every tap inside kmax is
        // above the cutoff by construction, so the two passes are branch-free.
        //
        // Keeping the taps in registers for the second pass was measured and
        // rejected: the unrolled array spends more instructions on the bounds
        // checks than the recurrence walk it saves, and it raised the ratio
        // from 1.88x to 2.36x on the dense case. Walking the recurrence twice
        // is cheaper than storing it.
        FLOAT sum = 1;
        FLOAT wu = 1, ru = rup, wd = 1, rd = rdn;

        for (int t = 1; t <= kmax; ++t) {
            wu *= ru;
            ru *= sp.iq;
            wd *= rd;
            rd *= sp.iq;
            sum += wu + wd;
        }

        const FLOAT scale = w / sum;
        soft_increment<ATOMIC>(&hist[m * stride], scale);

        wu = 1; ru = rup;
        wd = 1; rd = rdn;

        for (int t = 1; t <= kmax; ++t) {
            wu *= ru;
            ru *= sp.iq;
            wd *= rd;
            rd *= sp.iq;
            soft_increment<ATOMIC>(&hist[(m + t) * stride], wu * scale);
            soft_increment<ATOMIC>(&hist[(m - t) * stride], wd * scale);
        }

        return;
    }
    FLOAT sum = 1;
    FLOAT wu = 1, ru = rup;
    FLOAT wd = 1, rd = rdn;
    bool oku = true, okd = true;

    for (int t = 1; t <= kmax; ++t) {
        wu *= ru;
        ru *= sp.iq;
        wd *= rd;
        rd *= sp.iq;

        oku = (m + t < sp.nbins) && (wu > sp.cutoff);
        okd = (m - t >= 0) && (wd > sp.cutoff);

        if (oku) {
            sum += wu;
        }
        if (okd) {
            sum += wd;
        }
        if (!oku && !okd) {
            break;
        }
    }

    // float division of a double: keep it double, the histogram is double.
    const FLOAT scale = w / sum;

    soft_increment<ATOMIC>(&hist[m * stride], scale);

    wu = 1; ru = rup;
    wd = 1; rd = rdn;

    for (int t = 1; t <= kmax; ++t) {
        wu *= ru;
        ru *= sp.iq;
        wd *= rd;
        rd *= sp.iq;

        oku = (m + t < sp.nbins) && (wu > sp.cutoff);
        okd = (m - t >= 0) && (wd > sp.cutoff);

        if (oku) {
            soft_increment<ATOMIC>(&hist[(m + t) * stride], wu * scale);
        }
        if (okd) {
            soft_increment<ATOMIC>(&hist[(m - t) * stride], wd * scale);
        }
        if (!oku && !okd) {
            break;
        }
    }
}


// ============================================================================
// General (non-uniform) grid
// ============================================================================
//
// Arbitrary monotone edges have no arithmetic progression, so neither the
// nearest-centre formula nor the tap recurrence survives. What does survive is
// the truncation rule: a tap is kept while its logit stays within
// ln(1/cutoff) of the peak's, because exp(-(x_b - x_min)) is then still above
// `cutoff`. So the window is found by expanding outwards from the peak until
// that test fails, and the weights are exp() of the logit difference.
//
// The peak is the last centre not above s, refined by a short local descent:
// with per-bin sigma a *wide* neighbouring bin can have a lower logit than the
// bin that actually contains s, so "the bin containing s" is not always the
// peak. Two steps of descent suffice for sigma_i proportional to the local
// width and cost nothing when it is not needed.
//
// The cost model changes here: one exp per tap per pass instead of two exps per
// pair, which is why soft_taps='fast' exists (__expf, ~1e-6 relative).

struct SoftWindow {
    int m;      // peak bin
    int up;     // taps above m
    int dn;     // taps below m
    FLOAT lmin; // logit at the peak
};

__device__ __forceinline__ SoftWindow soft_general_window(
    const SoftBinSpec &sp,
    FLOAT s)
{
    const int nbins = sp.nbins;
    const FLOAT *cen = sp.centres;
    const FLOAT *i2s2 = sp.inv2s2;
    const FLOAT *edg = sp.edges;

    // Bin containing s: the last edge at or below it. Searching the centres
    // instead would answer "previous bin" for the lower half of every bin, which
    // a wide softmax hides but a narrow one does not.
    int lo = 0, hi = nbins - 1;

    while (lo < hi) {
        const int mid = (lo + hi + 1) >> 1;

        if (edg[mid] <= s) {
            lo = mid;
        }
        else {
            hi = mid - 1;
        }
    }

    int m = lo;
    FLOAT d = s - cen[m];

    SoftWindow win;
    win.lmin = d * d * i2s2[m];

    for (int it = 0; it < 2; ++it) {
        if (m > 0) {
            const FLOAT dd = s - cen[m - 1];
            const FLOAT l = dd * dd * i2s2[m - 1];

            if (l < win.lmin) {
                win.lmin = l;
                m -= 1;
                continue;
            }
        }

        if (m + 1 < nbins) {
            const FLOAT dd = s - cen[m + 1];
            const FLOAT l = dd * dd * i2s2[m + 1];

            if (l < win.lmin) {
                win.lmin = l;
                m += 1;
            }
        }
    }

    win.m = m;
    win.up = 0;
    win.dn = 0;

    const FLOAT thresh = sp.thresh;
    const int kmax = sp.kmax;

    while (win.up < kmax && m + win.up + 1 < nbins) {
        const FLOAT dd = s - cen[m + win.up + 1];

        if (dd * dd * i2s2[m + win.up + 1] - win.lmin > thresh) {
            break;
        }

        win.up += 1;
    }

    while (win.dn < kmax && m - win.dn - 1 >= 0) {
        const FLOAT dd = s - cen[m - win.dn - 1];

        if (dd * dd * i2s2[m - win.dn - 1] - win.lmin > thresh) {
            break;
        }

        win.dn += 1;
    }

    return win;
}


template <bool ATOMIC>
__device__ __forceinline__ void soft_add_general(
    FLOAT *hist,
    const SoftBinSpec &sp,
    FLOAT s,
    FLOAT w,
    const int stride)
{
    if (!(s >= sp.lo) || !(s < sp.hi)) {
        return;
    }

    const FLOAT *cen = sp.centres;
    const FLOAT *i2s2 = sp.inv2s2;
    const bool fast = sp.fast_taps != 0;
    const SoftWindow win = soft_general_window(sp, s);
    const int m = win.m;

    // Pass 1: the normaliser. The peak's weight is exp(0) = 1.
    FLOAT sum = 1;

    for (int k = 1; k <= win.up; ++k) {
        const FLOAT dd = s - cen[m + k];
        sum += soft_tap_weight(dd * dd * i2s2[m + k] - win.lmin, fast);
    }

    for (int k = 1; k <= win.dn; ++k) {
        const FLOAT dd = s - cen[m - k];
        sum += soft_tap_weight(dd * dd * i2s2[m - k] - win.lmin, fast);
    }

    // Pass 2: scatter. A second exp per tap, because the general path has no
    // recurrence to replay; soft_taps='fast' is the knob that makes it cheap.
    const FLOAT scale = w / sum;

    soft_increment<ATOMIC>(&hist[m * stride], scale);

    for (int k = 1; k <= win.up; ++k) {
        const FLOAT dd = s - cen[m + k];
        soft_increment<ATOMIC>(
            &hist[(m + k) * stride],
            scale * soft_tap_weight(dd * dd * i2s2[m + k] - win.lmin, fast));
    }

    for (int k = 1; k <= win.dn; ++k) {
        const FLOAT dd = s - cen[m - k];
        soft_increment<ATOMIC>(
            &hist[(m - k) * stride],
            scale * soft_tap_weight(dd * dd * i2s2[m - k] - win.lmin, fast));
    }
}


// The one entry the op calls: one predictable branch per pair picks the path,
// so the uniform kernel keeps its instruction stream and register count.
template <bool ATOMIC>
__device__ __forceinline__ void soft_add(
    FLOAT *hist,
    const SoftBinSpec &sp,
    FLOAT s,
    FLOAT w,
    const int stride)
{
    if (sp.uniform) {
        soft_add_uniform<ATOMIC>(hist, sp, s, w, stride);
    }
    else {
        soft_add_general<ATOMIC>(hist, sp, s, w, stride);
    }
}


// ============================================================================
// Multipole axis: soft mu binning
// ============================================================================
//
// mu is softened with the same truncated Gaussian softmax, on a uniform grid of
// nmu centres over [-1, 1] (the interval mu already lives in, so the grid needs
// no range search: the nearest centre is arithmetic). What the pair then
// accumulates is *not* a histogram in mu but the multipoles,
//
//   M_l = sum_j Wmu_j (2l + 1) P_l(mu_j),       sum_j Wmu_j = 1
//
// and the s scatter multiplies by M_l instead of by 1. Two consequences worth
// writing down, because they are the whole reason for this shape:
//
//  * the cost per pair is taps_s * nell histogram updates, not
//    taps_s * taps_mu: the mu profile is a per-pair scalar vector, folded in
//    before the scatter;
//  * P_0 = 1 and sum_j Wmu_j = 1, so M_0 = 1 exactly and the monopole of a soft
//    mu request is bit-for-bit the soft-s count. sigma_mu -> 0 therefore splits
//    the mu weight between the two neighbouring mu centres and reproduces the
//    hard multipoles up to that quadrature: the same limit as pyfcfc.

// P_l(centre) for every l <= ellmax, by Bonnet's recursion. The hard kernel's
// set_legendre() fills 0, 2, 4, 6, 8 on its even-ell fast path and leaves every
// other order at zero, which is fine there (its layout is contiguous from 0) but
// not here: a soft request may list any multipoles, in any order, so every
// requested order is filled in one pass.
__device__ __forceinline__ void soft_legendre_all(
    FLOAT *leg,
    const int ellmax,
    const FLOAT mu)
{
    leg[0] = 1;

    if (ellmax >= 1) {
        leg[1] = mu;
    }

    for (int ell = 2; ell <= ellmax; ++ell) {
        const FLOAT inv = 1 / (FLOAT) ell;
        leg[ell] = ((2 * ell - 1) * mu * leg[ell - 1] - (ell - 1) * leg[ell - 2]) * inv;
    }
}


// The truncated softmax over the mu grid folded onto the multipoles. DERIV also
// returns the derivative of the profile with respect to mu, which is what the
// adjoint needs:
//
//   M_l(mu) = sum_j Wmu_j(mu) (2l+1) P_l(c_j) / sum_j Wmu_j(mu)
//   dM_l/dmu = (dN_l - M_l dS) / S,   dS = sum_j dWmu_j/dmu
//   dN_l = sum_j dWmu_j/dmu (2l+1) P_l(c_j),   dWmu_j/dmu = Wmu_j (c_j - mu)/sigma^2
//
// Note that there is no dP_l/dmu term: the taps sit on the *fixed* mu grid, so
// the only thing that moves with mu is the Gaussian weight. (The hard kernel can
// evaluate P_l at the pair's own mu because there mu is a coordinate; here it is
// smoothed, and the multipole of a tap is the multipole of its centre.)
template <bool DERIV>
__device__ __forceinline__ void soft_mu_profile_uniform(
    const SoftBinSpec &sp,
    const FLOAT mu,
    FLOAT *M,
    FLOAT *dM)
{
    int m = (int) floor((mu - sp.mu_c0) * sp.mu_inv_dmu + 0.5);

    if (m < 0) {
        m = 0;
    }
    else if (m >= sp.nmu) {
        m = sp.nmu - 1;
    }

    const FLOAT u = mu - (sp.mu_c0 + m * sp.mu_dmu);

    // Same recurrence as a uniform s window: one exp for the upper ratio, the
    // lower one is iq / rup.
    const FLOAT md = (2 * u - sp.mu_dmu) * sp.mu_dmu * sp.mu_inv2sig2;
    const FLOAT rup = exp(md);
    const FLOAT rdn = (rup > 0) ? sp.mu_iq / rup : exp(-md - sp.mu_gg);
    const int kmax = sp.mu_kmax;
    const int nell = sp.nell;

    FLOAT num[CUCOUNT_SOFT_MAXELL], dnum[CUCOUNT_SOFT_MAXELL];
    FLOAT leg[CUCOUNT_SOFT_MAXELL];

    for (int ill = 0; ill < nell; ++ill) {
        num[ill] = 0;
        dnum[ill] = 0;
    }

    FLOAT sum = 1, dsum = 0;

    // `W` is the (unnormalised) weight of the tap, `B` its mu cell.
#define CUCOUNT_SOFT_MU_TAP(B, W)                                               \
    {                                                                           \
        const FLOAT m_ = sp.mu_c0 + (FLOAT) (B) * sp.mu_dmu;                     \
        soft_legendre_all(leg, sp.ell_max, m_);                            \
        const FLOAT dw_ = DERIV ? (W) * (m_ - mu) * 2 * sp.mu_inv2sig2 : (FLOAT) 0; \
                                                                                \
        for (int ill = 0; ill < nell; ++ill) {                                   \
            const int ell = sp.ells[ill];                                        \
            const FLOAT pf = (FLOAT) (2 * ell + 1);                              \
            num[ill] += (W) * pf * leg[ell];                                     \
                                                                                \
            if (DERIV) {                                                         \
                dnum[ill] += dw_ * pf * leg[ell];         \
            }                                                                    \
        }                                                                        \
                                                                                \
        if (DERIV) {                                                             \
            dsum += dw_;                                                         \
        }                                                                        \
    }

    CUCOUNT_SOFT_MU_TAP(m, 1);

    FLOAT wu = 1, ru = rup;
    FLOAT wd = 1, rd = rdn;

    for (int t = 1; t <= kmax; ++t) {
        wu *= ru;
        ru *= sp.mu_iq;
        wd *= rd;
        rd *= sp.mu_iq;

        const bool oku = (m + t < sp.nmu) && (wu > sp.cutoff);
        const bool okd = (m - t >= 0) && (wd > sp.cutoff);

        if (oku) {
            sum += wu;
            CUCOUNT_SOFT_MU_TAP(m + t, wu);
        }

        if (okd) {
            sum += wd;
            CUCOUNT_SOFT_MU_TAP(m - t, wd);
        }

        if (!oku && !okd) {
            break;
        }
    }

#undef CUCOUNT_SOFT_MU_TAP

    const FLOAT inv = 1 / sum;

    for (int ill = 0; ill < nell; ++ill) {
        M[ill] = num[ill] * inv;

        if (DERIV) {
            dM[ill] = (dnum[ill] - M[ill] * dsum) * inv;
        }
    }
}


// The same profile on a caller-supplied (non-arithmetic) mu grid. There is no
// multiplicative recurrence across unequal cells, so the window is expanded cell
// by cell and each tap pays one exp; the tap set is still the truncated softmax
// (every cell whose weight is above the cutoff), and the derivative keeps the
// same form with the tap's own sigma:
//
//   dWmu_j/dmu = Wmu_j (c_j - mu) / sigma_j^2.
template <bool DERIV>
__device__ __forceinline__ void soft_mu_profile_general(
    const SoftBinSpec &sp,
    const FLOAT mu,
    FLOAT *M,
    FLOAT *dM)
{
    const int nmu = sp.nmu;
    const FLOAT *cen = sp.mu_centres;
    const FLOAT *i2s2 = sp.mu_inv2s2;
    const int nell = sp.nell;
    const bool fast = sp.fast_taps != 0;

    // Arbitrary edges can make neighbouring cells very different widths, so the
    // logit is not monotone in the cell index: a local peak search would stop on
    // the wrong side of a wide cell and miss contributing cells. Scan the whole
    // grid instead -- the minimum logit, then every cell within the cutoff of it.
    // This path is opt-in (an arithmetic grid keeps the two-exp recurrence) and
    // nmu is capped at 1024, so the extra pass stays cheap next to the s window.
    FLOAT lmin = (mu - cen[0]) * (mu - cen[0]) * i2s2[0];

    for (int j = 1; j < nmu; ++j) {
        const FLOAT d = mu - cen[j];
        const FLOAT l = d * d * i2s2[j];

        if (l < lmin) {
            lmin = l;
        }
    }

    FLOAT num[CUCOUNT_SOFT_MAXELL], dnum[CUCOUNT_SOFT_MAXELL];
    FLOAT leg[CUCOUNT_SOFT_MAXELL];

    for (int ill = 0; ill < nell; ++ill) {
        num[ill] = 0;
        dnum[ill] = 0;
    }

    FLOAT sum = 0, dsum = 0;

    // `W` is the unnormalised weight of the tap, `B` its mu cell; `l` its logit
    // relative to the peak, so `W = exp(-l)`.
#define CUCOUNT_SOFT_MU_TAP_G(B, W, L)                                          \
    {                                                                           \
        soft_legendre_all(leg, sp.ell_max, cen[B]);                             \
        const FLOAT dw_ = DERIV ? (W) * (cen[B] - mu) * 2 * i2s2[B] : (FLOAT) 0; \
                                                                                \
        for (int ill = 0; ill < nell; ++ill) {                                   \
            const int ell = sp.ells[ill];                                        \
            const FLOAT pf = (FLOAT) (2 * ell + 1);                              \
            num[ill] += (W) * pf * leg[ell];                                     \
                                                                                \
            if (DERIV) {                                                         \
                dnum[ill] += dw_ * pf * leg[ell];                                \
            }                                                                    \
        }                                                                        \
                                                                                \
        if (DERIV) {                                                             \
            dsum += dw_;                                                         \
        }                                                                        \
    }

    for (int j = 0; j < nmu; ++j) {
        const FLOAT d = mu - cen[j];
        const FLOAT l = d * d * i2s2[j] - lmin;

        if (!(l <= sp.thresh)) {
            continue;
        }

        const FLOAT w = fast ? __expf(-l) : exp(-l);
        sum += w;
        CUCOUNT_SOFT_MU_TAP_G(j, w, l);
    }

#undef CUCOUNT_SOFT_MU_TAP_G

    const FLOAT inv = 1 / sum;

    for (int ill = 0; ill < nell; ++ill) {
        M[ill] = num[ill] * inv;

        if (DERIV) {
            dM[ill] = (dnum[ill] - M[ill] * dsum) * inv;
        }
    }
}


// Dispatch: the arithmetic grid keeps the two-exp recurrence, anything else the
// per-tap window. Both fill the same M/dM contract.
template <bool DERIV>
__device__ __forceinline__ void soft_mu_profile(
    const SoftBinSpec &sp,
    const FLOAT mu,
    FLOAT *M,
    FLOAT *dM)
{
    if (sp.mu_uniform) {
        soft_mu_profile_uniform<DERIV>(sp, mu, M, dM);
    }
    else {
        soft_mu_profile_general<DERIV>(sp, mu, M, dM);
    }
}


// Soft-s scatter of a pair whose multipole profile is already known: the s
// window is walked once per multipole (the sum that normalises it does not
// depend on l), so the extra work over a plain soft-s pair is nell - 1 window
// walks, and the atomics are exactly taps_s * nell either way.
template <bool ATOMIC>
__device__ __forceinline__ void soft_add_pole(
    FLOAT *hist,
    const SoftBinSpec &sp,
    FLOAT s,
    FLOAT mu,
    FLOAT w)
{
    if (!(s >= sp.lo) || !(s < sp.hi)) {
        return;
    }

    FLOAT M[CUCOUNT_SOFT_MAXELL];

    soft_mu_profile<false>(sp, mu, M, M);

    for (int ill = 0; ill < sp.nell; ++ill) {
        soft_add<ATOMIC>(hist + ill, sp, s, w * M[ill], sp.nell);
    }
}


// ============================================================================
// Pair counting op
// ============================================================================

template <bool ATOMIC>
struct Count2SoftOp {
    FLOAT *hist;

    FLOAT *position1;
    FLOAT *sposition1;
    FLOAT *value1;

    IndexValue index_value1;
    IndexValue index_value2;

    WeightAttrs wattrs;
    SelectionAttrs sattrs;
    MeshAttrs mattrs;

    SoftBinSpec spec;

    __device__ inline void operator()(
        size_t jj,
        FLOAT *position2,
        FLOAT *sposition2,
        FLOAT *value2)
    {
        (void) jj;

        if (!is_selected_pair(
                sposition1,
                sposition2,
                position1,
                position2,
                sattrs,
                mattrs)) {
            return;
        }

        FLOAT diff[NDIM];
        difference(diff, position2, position1, mattrs);

        const FLOAT s = sqrt(dot(diff, diff));

        FLOAT pair_weight = 1.;

        if (index_value1.size_individual_weight) {
            pair_weight *= value1[index_value1.start_individual_weight];
        }

        if (index_value2.size_individual_weight) {
            pair_weight *= value2[index_value2.start_individual_weight];
        }

        if (index_value1.size_bitwise_weight &&
            index_value2.size_bitwise_weight) {
            pair_weight *= pair_bitwise_weight(
                value1,
                value2,
                index_value1,
                index_value2,
                wattrs.bitwise);
        }

        // Linear in the pair weight, so the negative-weight correction is one
        // more subtraction before the scatter, not a second pass: the soft
        // weights sum to one, so w * 1 is conserved either way.
        if (index_value1.size_negative_weight &&
            index_value2.size_negative_weight) {
            pair_weight -=
                value1[index_value1.start_negative_weight] *
                value2[index_value2.start_negative_weight];
        }

        if (spec.nell > 0) {
            // The pair's mu, measured exactly as the hard kernel measures it, so
            // the soft multipoles and the hard ones see the same line of sight.
            FLOAT mu = 0., mu2 = 0.;

            compute_pair_mu(diff, sposition1, sposition2, position1, position2,
                            spec.los, s, s * s, true, &mu, &mu2);

            soft_add_pole<ATOMIC>(hist, spec, s, mu, pair_weight);
        }
        else {
            soft_add<ATOMIC>(hist, spec, s, pair_weight, 1);
        }
    }
};


// ============================================================================
// Kernels
// ============================================================================
//
// USE_SHARED gives each block a private histogram tile in shared memory, flushed
// to the global histogram once per block. That is the whole point of the design:
// measured on an A40, a double atomicAdd into shared memory is 8-20x cheaper
// than one into global memory, and its cost is flat in the number of bins, while
// the global one grows with them. Soft binning issues 2*kmax+1 atomics per pair
// instead of one, so without the tile it would be several times the hard cost.
//
// The tile has to hold the whole histogram, so wide binnings fall back to
// direct global atomics (path 1). The binding decides which, and reports it.

// REP is how many private copies of the histogram a warp keeps: REP == 32 gives
// every lane its own row (no atomics at all), smaller values fold some lanes
// together (still an atomic, but only REP-way contended instead of block-wide),
// and REP == 0 scatters straight into global memory, which is the only option
// once the histogram no longer fits in shared memory.
//
// Why this matters: measured on an A40, one double atomicAdd into a shared tile
// costs about 0.36 ns, which is what the extra 2*kmax taps of a soft scatter
// cost on top of the hard kernel's single scatter. Removing the atomic from the
// tap loop is therefore the difference between "soft costs 1 + 0.36 ns * taps
// per pair" and "soft costs one geometry pass plus a few shared stores".
#define CUCOUNT_SOFT_MAXWARP 32

template <MESH_TYPE TARGET_MESH_TYPE, int REP>
__global__ void count2_soft_kernel(
    FLOAT *counts,
    Mesh mesh1,
    Mesh mesh2,
    MeshAttrs mattrs,
    SelectionAttrs sattrs,
    WeightAttrs wattrs,
    SoftBinSpec spec)
{
    extern __shared__ FLOAT tile[];

    constexpr bool ATOMIC = (REP != 32);
    // Histogram entries, i.e. s bins times multipoles: the tile, the row stride
    // and the reduction all work on the flat slot index.
    const int nbins = spec.nslots;
    const int nwarps = blockDim.x / CUCOUNT_SOFT_MAXWARP;
    const int nrows = nwarps * (REP > 0 ? REP : 1);

    if constexpr (REP > 0) {
        for (int i = threadIdx.x; i < nrows * nbins; i += blockDim.x) {
            tile[i] = 0;
        }

        __syncthreads();
    }

    FLOAT *hist = counts;

    if constexpr (REP > 0) {
        // Row per lane when REP == 32, otherwise lane % REP lanes share a row.
        const int lane = threadIdx.x & (CUCOUNT_SOFT_MAXWARP - 1);
        const int warp = threadIdx.x / CUCOUNT_SOFT_MAXWARP;
        hist = &tile[(warp * REP + (lane & (REP - 1))) * nbins];
    }

    const size_t stride = gridDim.x * blockDim.x;
    const size_t gid = threadIdx.x + blockIdx.x * blockDim.x;

    for (size_t ii = gid; ii < mesh1.total_nparticles; ii += stride) {
        FLOAT *position1  = &(mesh1.positions[NDIM * ii]);
        FLOAT *sposition1 = &(mesh1.spositions[NDIM * ii]);
        FLOAT *value1     = &(mesh1.values[mesh1.index_value.size * ii]);

        Count2SoftOp<ATOMIC> op{
            hist,
            position1,
            sposition1,
            value1,
            mesh1.index_value,
            mesh2.index_value,
            wattrs,
            sattrs,
            mattrs,
            spec
        };

        for_each_candidate<TARGET_MESH_TYPE>(
            position1,
            sposition1,
            mesh2,
            mattrs,
            op);
    }

    if constexpr (REP > 0) {
        __syncthreads();

        for (int i = threadIdx.x; i < nbins; i += blockDim.x) {
            FLOAT acc = 0;

            for (int r = 0; r < nrows; ++r) {
                acc += tile[r * nbins + i];
            }

            if (acc != 0) {
                atomicAdd(&counts[i], acc);
            }
        }
    }
}


// ============================================================================
// Host entry point
// ============================================================================

template <MESH_TYPE TARGET_MESH_TYPE, int REP>
static void launch_soft(
    FLOAT *counts,
    const Mesh *list_mesh,
    const MeshAttrs &mattrs,
    const SelectionAttrs &sattrs,
    const WeightAttrs &wattrs,
    const SoftBinSpec &spec,
    int nblocks,
    int nthreads_per_block,
    size_t shmem,
    cudaStream_t stream)
{
    count2_soft_kernel<TARGET_MESH_TYPE, REP><<<
        nblocks,
        nthreads_per_block,
        shmem,
        stream>>>(
            counts,
            list_mesh[0],
            list_mesh[1],
            mattrs,
            sattrs,
            wattrs,
            spec);
}


// How many private copies of the histogram each warp keeps. More copies means
// less atomic contention but more shared memory, and shared memory is the
// occupancy currency: a per-lane tile of a 20-bin double histogram is 5 kB per
// warp, which caps the block at two per SM and costs more than the atomics it
// saves. The budget below is the empirically useful middle: contention drops by
// 8x to 32x while four or more blocks stay resident.
static const size_t soft_tile_budget = 12288;

static int pick_rep(const SoftBinSpec &spec, int nthreads_per_block, size_t budget)
{
    const int nwarps = nthreads_per_block / CUCOUNT_SOFT_MAXWARP;

    if (nwarps < 1) {
        return 0;
    }

    for (int rep : {8, 4, 2, 1}) {
        const size_t bytes = (size_t) nwarps * rep * spec.nslots * sizeof(FLOAT);

        if (bytes <= budget) {
            return rep;
        }
    }

    return 0;
}


// The general path needs the centres and 1/(2 sigma_i^2) on the device. They are
// rebuilt per call instead of being cached: the python path allocates a fresh
// buffer each time and the FFI path rewinds one shared buffer, so "per call" is
// the only lifetime that is correct for both. The upload is a few kB against a
// pass over millions of pairs, and it goes on `stream` so the kernel below
// cannot read a half-written table (a synchronous copy on the legacy stream
// would be unordered against the kernel, which is exactly the bug the mesh code
// had).
static void upload_soft_tables(SoftBinSpec &spec, DeviceMemoryBuffer *buffer,
                               cudaStream_t stream)
{
    if (!spec.uniform) {
        const size_t n = (size_t) spec.nbins;
        FLOAT *d_centres = (FLOAT *) my_device_malloc(n * sizeof(FLOAT), buffer);
        FLOAT *d_inv2s2 = (FLOAT *) my_device_malloc(n * sizeof(FLOAT), buffer);
        FLOAT *d_edges = (FLOAT *) my_device_malloc((n + 1) * sizeof(FLOAT), buffer);
        std::vector<FLOAT> h_centres(n), h_inv2s2(n);

        for (size_t i = 0; i < n; ++i) {
            const double e0 = (double) spec.host_edges[i];
            const double e1 = (double) spec.host_edges[i + 1];
            // sigma_i proportional to the local width unless the caller asked for
            // one absolute sigma. Both land in the same array, so the kernel has a
            // single code path.
            const double sigma = spec.per_bin_sigma
                ? (double) spec.alpha * (e1 - e0)
                : (double) spec.sigma;

            h_centres[i] = (FLOAT) (0.5 * (e0 + e1));
            h_inv2s2[i] = (FLOAT) (1. / (2. * sigma * sigma));
        }

        CUDA_CHECK(cudaMemcpyAsync(d_centres, h_centres.data(), n * sizeof(FLOAT),
                                   cudaMemcpyHostToDevice, stream));
        CUDA_CHECK(cudaMemcpyAsync(d_inv2s2, h_inv2s2.data(), n * sizeof(FLOAT),
                                   cudaMemcpyHostToDevice, stream));
        CUDA_CHECK(cudaMemcpyAsync(d_edges, spec.host_edges, (n + 1) * sizeof(FLOAT),
                                   cudaMemcpyHostToDevice, stream));

        spec.centres = d_centres;
        spec.inv2s2 = d_inv2s2;
        spec.edges = d_edges;
    }

    // The mu grid needs the same treatment when it is not arithmetic: centres,
    // per-cell 1/(2 sigma_j^2) and the edges the window search walks.
    if (spec.nell > 0 && !spec.mu_uniform) {
        const size_t n = (size_t) spec.nmu;
        FLOAT *d_centres = (FLOAT *) my_device_malloc(n * sizeof(FLOAT), buffer);
        FLOAT *d_inv2s2 = (FLOAT *) my_device_malloc(n * sizeof(FLOAT), buffer);
        FLOAT *d_edges = (FLOAT *) my_device_malloc((n + 1) * sizeof(FLOAT), buffer);
        std::vector<FLOAT> h_centres(n), h_inv2s2(n);

        for (size_t i = 0; i < n; ++i) {
            const double e0 = (double) spec.host_mu_edges[i];
            const double e1 = (double) spec.host_mu_edges[i + 1];
            const double sigma = spec.mu_per_bin_sigma
                ? (double) spec.mu_alpha * (e1 - e0)
                : (double) spec.mu_sigma;

            h_centres[i] = (FLOAT) (0.5 * (e0 + e1));
            h_inv2s2[i] = (FLOAT) (1. / (2. * sigma * sigma));
        }

        CUDA_CHECK(cudaMemcpyAsync(d_centres, h_centres.data(), n * sizeof(FLOAT),
                                   cudaMemcpyHostToDevice, stream));
        CUDA_CHECK(cudaMemcpyAsync(d_inv2s2, h_inv2s2.data(), n * sizeof(FLOAT),
                                   cudaMemcpyHostToDevice, stream));
        CUDA_CHECK(cudaMemcpyAsync(d_edges, spec.host_mu_edges, (n + 1) * sizeof(FLOAT),
                                   cudaMemcpyHostToDevice, stream));

        spec.mu_centres = d_centres;
        spec.mu_inv2s2 = d_inv2s2;
        spec.mu_edge_table = d_edges;
    }
}


// Inside a DeviceMemoryBuffer my_device_free is a no-op (the whole buffer is
// released by its owner), so this only really frees the cudaMalloc fallback --
// and, because cudaFree synchronises, that also guarantees the kernel has read
// the tables before they go away.
static void release_soft_tables(SoftBinSpec &spec, DeviceMemoryBuffer *buffer)
{
    if (spec.centres) {
        my_device_free(spec.centres, buffer);
        spec.centres = nullptr;
    }

    if (spec.inv2s2) {
        my_device_free(spec.inv2s2, buffer);
        spec.inv2s2 = nullptr;
    }

    if (spec.edges) {
        my_device_free(spec.edges, buffer);
        spec.edges = nullptr;
    }

    if (spec.mu_centres) {
        my_device_free(spec.mu_centres, buffer);
        spec.mu_centres = nullptr;
    }

    if (spec.mu_inv2s2) {
        my_device_free(spec.mu_inv2s2, buffer);
        spec.mu_inv2s2 = nullptr;
    }

    if (spec.mu_edge_table) {
        my_device_free(spec.mu_edge_table, buffer);
        spec.mu_edge_table = nullptr;
    }
}


void count2_soft(
    FLOAT *counts,
    const Mesh *list_mesh,
    const Count2Attrs &attrs,
    SoftBinSpec &spec,
    DeviceMemoryBuffer *buffer,
    cudaStream_t stream)
{
    const MeshAttrs mattrs = attrs.mattrs;
    const SelectionAttrs sattrs = attrs.sattrs;
    const WeightAttrs wattrs = attrs.wattrs;

    const size_t csize = (size_t) spec.nslots;

    CUDA_CHECK(cudaMemsetAsync(counts, 0, csize * sizeof(FLOAT), stream));

    upload_soft_tables(spec, buffer, stream);

    int nblocks, nthreads_per_block;

    if (mattrs.type == MESH_ANGULAR) {
        CONFIGURE_KERNEL_LAUNCH(
            (count2_soft_kernel<MESH_ANGULAR, 1>),
            nblocks,
            nthreads_per_block,
            buffer);
    }
    else {
        CONFIGURE_KERNEL_LAUNCH(
            (count2_soft_kernel<MESH_CARTESIAN, 1>),
            nblocks,
            nthreads_per_block,
            buffer);
    }

    int dev = 0;
    cudaGetDevice(&dev);

    int rep = pick_rep(spec, nthreads_per_block, soft_tile_budget);

    // Bench hooks: the winning number of copies is machine dependent, so allow
    // an override and report what was used instead of guessing silently.
    if (const char *env = std::getenv("CUCOUNT_SOFT_REP")) {
        rep = std::atoi(env);
    }

    // A tile that does not fit is not a tile: fall back rather than launch a
    // kernel that cannot run. (An override from CUCOUNT_SOFT_REP lands here too.)
    int max_shmem = 48 * 1024;
    cudaDeviceGetAttribute(&max_shmem, cudaDevAttrMaxSharedMemoryPerBlock, dev);
    const int nwarps = nthreads_per_block / CUCOUNT_SOFT_MAXWARP;

    if (rep > 0) {
        int fits = 0;

        for (int cand : {16, 8, 4, 2, 1}) {
            if (cand <= rep && (size_t) nwarps * cand * csize * sizeof(FLOAT) <= (size_t) max_shmem) {
                fits = cand;
                break;
            }
        }

        rep = fits;
    }

    spec.path = rep;  // reported back to the caller: 0 = global, else private copies
    const size_t shmem = rep > 0
        ? (size_t) nwarps * rep * csize * sizeof(FLOAT)
        : 0;

    // No device-wide synchronisation and no event timing here: the python caller
    // times itself around a stream sync, and the jax FFI path runs inside a
    // stream XLA owns, where blocking the device is not allowed.
#define CUCOUNT_LAUNCH_SOFT(MESH, REPV)                                     \
    launch_soft<MESH, REPV>(                                                \
        counts, list_mesh, mattrs, sattrs, wattrs, spec,                    \
        nblocks, nthreads_per_block, shmem, stream)

    if (mattrs.type == MESH_ANGULAR) {
        if (rep == 32) {
            CUCOUNT_LAUNCH_SOFT(MESH_ANGULAR, 32);
        }
        else if (rep == 8) {
            CUCOUNT_LAUNCH_SOFT(MESH_ANGULAR, 8);
        }
        else if (rep == 4) {
            CUCOUNT_LAUNCH_SOFT(MESH_ANGULAR, 4);
        }
        else if (rep == 2) {
            CUCOUNT_LAUNCH_SOFT(MESH_ANGULAR, 2);
        }
        else if (rep == 1) {
            CUCOUNT_LAUNCH_SOFT(MESH_ANGULAR, 1);
        }
        else {
            CUCOUNT_LAUNCH_SOFT(MESH_ANGULAR, 0);
        }
    }
    else {
        if (rep == 32) {
            CUCOUNT_LAUNCH_SOFT(MESH_CARTESIAN, 32);
        }
        else if (rep == 8) {
            CUCOUNT_LAUNCH_SOFT(MESH_CARTESIAN, 8);
        }
        else if (rep == 4) {
            CUCOUNT_LAUNCH_SOFT(MESH_CARTESIAN, 4);
        }
        else if (rep == 2) {
            CUCOUNT_LAUNCH_SOFT(MESH_CARTESIAN, 2);
        }
        else if (rep == 1) {
            CUCOUNT_LAUNCH_SOFT(MESH_CARTESIAN, 1);
        }
        else {
            CUCOUNT_LAUNCH_SOFT(MESH_CARTESIAN, 0);
        }
    }

#undef CUCOUNT_LAUNCH_SOFT

    // Peek, do not consume: the caller's stream sync (pybind) or the FFI
    // handler's cudaGetLastError() must still see the failure. Reading it here
    // would clear it and hand back a silently zero histogram.
    cudaError_t last_error = cudaPeekAtLastError();

    if (last_error != cudaSuccess) {
        log_message(LOG_LEVEL_ERROR, "count2_soft launch failed: %s\n",
                    cudaGetErrorString(last_error));
    }

    release_soft_tables(spec, buffer);
}


// ============================================================================
// Adjoint (vector-Jacobian product)
// ============================================================================
//
// The forward is a scatter of one pair weight into a Gaussian window, so the
// adjoint is a gather of the histogram cotangent over the same window. Writing
// the softmax out (c_b centres, W_b = e_b / sum, cbar/xbar the W-means of the
// centres and logits):
//
//   dL/dw_pair = sum_b g_b W_b
//   dL/ds      = (w_pair / sigma^2) sum_b g_b W_b (c_b - cbar)
//   dL/dsigma  = (2 w_pair / sigma) sum_b g_b W_b (x_b - xbar)
//
// which is pyfcfc's soft_hist_vjp. Membership of the window and the [smin, smax)
// range check are piecewise constant in s, so they are held fixed (the usual
// convention), while the window's own renormalisation is differentiated exactly
// by summing over the same taps the forward used.
//
// Two passes, as in the forward: one for the normaliser and one for the five
// sums the formulas need. The pair sums collapse to
//   sum_b g W (c_b - cbar) = Tcg - cbar * A   with Tcg = sum_b g W c_b
//   sum_b g W (x_b - xbar) = Txg - xbar * A   with Txg = sum_b g W x_b
// so nothing is stored, just accumulated.
struct SoftVjpPair {
    FLOAT dw;
    FLOAT ds;
    FLOAT dsigma;
    FLOAT dmu;  // dL/dmu: only nonzero with soft mu binning
};


__device__ __forceinline__ void soft_vjp_pair_uniform(
    const FLOAT *g,
    const SoftBinSpec &sp,
    FLOAT s,
    FLOAT w,
    SoftVjpPair *out)
{
    out->dw = 0;
    out->ds = 0;
    out->dsigma = 0;
    out->dmu = 0;

    if (!(s >= sp.lo) || !(s < sp.hi)) {
        return;
    }

    int m = (int) floor((s - sp.c0) * sp.inv_ds + 0.5);

    if (m < 0) {
        m = 0;
    }
    else if (m >= sp.nbins) {
        m = sp.nbins - 1;
    }

    const FLOAT u = s - (sp.c0 + m * sp.ds);
    const FLOAT md = (2 * u - sp.ds) * sp.ds * sp.inv2sig2;
    const FLOAT rup = exp(md);
    const FLOAT rdn = (rup > 0) ? sp.iq / rup : exp(-md - sp.gg);
    const int kmax = sp.kmax;

    // Pass 1: the normaliser, exactly the sum the forward divides by.
    FLOAT sum = 1;
    FLOAT wu = 1, ru = rup, wd = 1, rd = rdn;

    for (int t = 1; t <= kmax; ++t) {
        wu *= ru;
        ru *= sp.iq;
        wd *= rd;
        rd *= sp.iq;

        const bool oku = (m + t < sp.nbins) && (wu > sp.cutoff);
        const bool okd = (m - t >= 0) && (wd > sp.cutoff);

        if (oku) {
            sum += wu;
        }
        if (okd) {
            sum += wd;
        }
        if (!oku && !okd) {
            break;
        }
    }

    const FLOAT scale = 1 / sum;

    // Pass 2: the cotangent sums. x_b = (s - c_b)^2 / (2 sigma^2).
    FLOAT A = 0;
    FLOAT cbar = 0;
    FLOAT xbar = 0;
    FLOAT tcg = 0;
    FLOAT txg = 0;

#define CUCOUNT_SOFT_VJP_TAP(B, W)                                \
    do {                                                          \
        const FLOAT c_ = sp.c0 + (B) * sp.ds;                     \
        const FLOAT d_ = s - c_;                                  \
        const FLOAT x_ = d_ * d_ * sp.inv2sig2;                   \
        const FLOAT w_ = (W) * scale;                             \
        const FLOAT g_ = g[B];                                    \
        A += w_ * g_;                                             \
        cbar += w_ * c_;                                          \
        xbar += w_ * x_;                                          \
        tcg += w_ * g_ * c_;                                      \
        txg += w_ * g_ * x_;                                      \
    } while (0)

    CUCOUNT_SOFT_VJP_TAP(m, 1);

    wu = 1; ru = rup;
    wd = 1; rd = rdn;

    for (int t = 1; t <= kmax; ++t) {
        wu *= ru;
        ru *= sp.iq;
        wd *= rd;
        rd *= sp.iq;

        const bool oku = (m + t < sp.nbins) && (wu > sp.cutoff);
        const bool okd = (m - t >= 0) && (wd > sp.cutoff);

        if (oku) {
            CUCOUNT_SOFT_VJP_TAP(m + t, wu);
        }
        if (okd) {
            CUCOUNT_SOFT_VJP_TAP(m - t, wd);
        }
        if (!oku && !okd) {
            break;
        }
    }

#undef CUCOUNT_SOFT_VJP_TAP

    // 1 / sigma^2 = 2 * inv2sig2, so no second division is needed.
    out->dw = A;
    out->ds = w * (tcg - cbar * A) * 2 * sp.inv2sig2;
    out->dsigma = w * (txg - xbar * A) * 2 * sp.inv_sigma;
    out->dmu = 0;
}


// General (non-uniform) adjoint: the same window as the forward -- it comes from
// the same helper, which is what keeps finite differences honest -- and the
// per-bin-sigma reduction derived in the header.
__device__ __forceinline__ void soft_vjp_pair_general(
    const FLOAT *g,
    const SoftBinSpec &sp,
    FLOAT s,
    FLOAT w,
    SoftVjpPair *out)
{
    out->dw = 0;
    out->ds = 0;
    out->dsigma = 0;
    out->dmu = 0;

    if (!(s >= sp.lo) || !(s < sp.hi)) {
        return;
    }

    const FLOAT *cen = sp.centres;
    const FLOAT *i2s2 = sp.inv2s2;
    const bool fast = sp.fast_taps != 0;
    const SoftWindow win = soft_general_window(sp, s);
    const int m = win.m;

    // Pass 1: the normaliser, exactly the sum the forward divides by.
    FLOAT sum = 1;

    for (int k = 1; k <= win.up; ++k) {
        const FLOAT dd = s - cen[m + k];
        sum += soft_tap_weight(dd * dd * i2s2[m + k] - win.lmin, fast);
    }

    for (int k = 1; k <= win.dn; ++k) {
        const FLOAT dd = s - cen[m - k];
        sum += soft_tap_weight(dd * dd * i2s2[m - k] - win.lmin, fast);
    }

    const FLOAT scale = 1 / sum;

    FLOAT A = 0;     // sum_b g_b W_b
    FLOAT cbar = 0;  // sum_b W_b c_b
    FLOAT xbar = 0;  // sum_b W_b x_b
    FLOAT tcg = 0;   // sum_b g_b W_b c_b
    FLOAT txg = 0;   // sum_b g_b W_b x_b
    FLOAT T = 0;     // sum_b g_b W_b (c_b - s) / sigma_b^2
    FLOAT U = 0;     // sum_b W_b (s - c_b) / sigma_b^2

#define CUCOUNT_SOFT_VJP_GEN_TAP(B, W)                            \
    do {                                                          \
        const FLOAT c_ = cen[B];                                  \
        const FLOAT d_ = s - c_;                                  \
        const FLOAT i2_ = i2s2[B];                                \
        const FLOAT x_ = d_ * d_ * i2_;                           \
        const FLOAT w_ = (W) * scale;                             \
        const FLOAT g_ = g[B];                                    \
        A += w_ * g_;                                             \
        cbar += w_ * c_;                                          \
        xbar += w_ * x_;                                          \
        tcg += w_ * g_ * c_;                                      \
        txg += w_ * g_ * x_;                                      \
        T += w_ * g_ * (c_ - s) * i2_;                            \
        U += w_ * (s - c_) * i2_;                                 \
    } while (0)

    CUCOUNT_SOFT_VJP_GEN_TAP(m, 1);

    for (int k = 1; k <= win.up; ++k) {
        const FLOAT dd = s - cen[m + k];
        CUCOUNT_SOFT_VJP_GEN_TAP(
            m + k, soft_tap_weight(dd * dd * i2s2[m + k] - win.lmin, fast));
    }

    for (int k = 1; k <= win.dn; ++k) {
        const FLOAT dd = s - cen[m - k];
        CUCOUNT_SOFT_VJP_GEN_TAP(
            m - k, soft_tap_weight(dd * dd * i2s2[m - k] - win.lmin, fast));
    }

#undef CUCOUNT_SOFT_VJP_GEN_TAP

    out->dw = A;
    out->ds = 2 * w * (T + A * U);
    out->dmu = 0;

    // With sigma_i taken from the bin widths there is no sigma to differentiate.
    if (!sp.per_bin_sigma) {
        out->dsigma = w * (txg - xbar * A) * 2 * sp.inv_sigma;
    }
}


// The line of sight as a unit vector plus the two coefficients that carry its
// own dependence on the endpoints. mu = (diff . lhat) / s, so
//
//   d mu / d diff_b   = (lhat_b - mu rhat_b) / s,     rhat = diff / s
//   d mu / d lhat_b   = rhat_b
//
// and lhat depends on a position only for the pair-dependent lines of sight
// (first point, end point, midpoint): lhat = r / |r| there, so
// d lhat_c / d r_b = (delta_bc - lhat_b lhat_c) / |r|, which is the `k1`/`k2`
// coefficient below (zero for the fixed x/y/z axes).
__device__ __forceinline__ void soft_mu_line_of_sight(
    const LOS_TYPE los,
    const FLOAT *sposition1,
    const FLOAT *sposition2,
    const FLOAT *position1,
    const FLOAT *position2,
    FLOAT *lhat,
    FLOAT *k1,
    FLOAT *k2)
{
    *k1 = 0;
    *k2 = 0;

    for (int axis = 0; axis < NDIM; ++axis) {
        lhat[axis] = 0;
    }

    if (los == LOS_FIRSTPOINT) {
        // The mesh already stores the unit position of each particle.
        for (int axis = 0; axis < NDIM; ++axis) {
            lhat[axis] = sposition1[axis];
        }

        const FLOAT r = sqrt(dot3(position1, position1));

        if (r > 0) {
            *k1 = 1 / r;
        }
    }
    else if (los == LOS_ENDPOINT) {
        for (int axis = 0; axis < NDIM; ++axis) {
            lhat[axis] = sposition2[axis];
        }

        const FLOAT r = sqrt(dot3(position2, position2));

        if (r > 0) {
            *k2 = 1 / r;
        }
    }
    else if (los == LOS_MIDPOINT) {
        FLOAT v[NDIM];

        add3(v, position1, position2);

        const FLOAT r = sqrt(dot3(v, v));

        if (r > 0) {
            for (int axis = 0; axis < NDIM; ++axis) {
                lhat[axis] = v[axis] / r;
            }

            *k1 = 1 / r;
            *k2 = 1 / r;
        }
    }
    else if (los == LOS_X) {
        lhat[0] = 1;
    }
    else if (los == LOS_Y) {
        lhat[1] = 1;
    }
    else {
        // LOS_Z, and the default for a request that reached here without one.
        lhat[NDIM - 1] = 1;
    }
}


// Adjoint of a pair counted with soft mu binning. The multipole profile is
// gathered through the same truncated mu window the forward used, and the
// cotangent is contracted with it in two directions at once:
//
//   * against M_ill, which is what the s adjoint sees (`g` becomes
//     `geff_b = sum_ill g[b,ill] M_ill`), so the s formulas are unchanged;
//   * against dM_ill/dmu, which is the mu cotangent the position update needs,
//     dL/dmu = w sum_ill (sum_b g[b,ill] Ws_b) dM_ill/dmu.
//
// Both come out of a single walk of the s window: the sums that carry `ill` are
// accumulated per multipole and contracted with M afterwards.
__device__ __forceinline__ void soft_vjp_pair_pole(
    const FLOAT *g,
    const SoftBinSpec &sp,
    FLOAT s,
    FLOAT mu,
    FLOAT w,
    SoftVjpPair *out)
{
    out->dw = 0;
    out->ds = 0;
    out->dsigma = 0;
    out->dmu = 0;

    if (!(s >= sp.lo) || !(s < sp.hi)) {
        return;
    }

    FLOAT M[CUCOUNT_SOFT_MAXELL], dM[CUCOUNT_SOFT_MAXELL];

    soft_mu_profile<true>(sp, mu, M, dM);

    const int nell = sp.nell;

    // Per multipole: sum_b W_b g[b,ill], and the two sums the s formula needs.
    FLOAT Bl[CUCOUNT_SOFT_MAXELL];
    FLOAT tcg_l[CUCOUNT_SOFT_MAXELL];
    FLOAT txg_l[CUCOUNT_SOFT_MAXELL];
    FLOAT T_l[CUCOUNT_SOFT_MAXELL];

    for (int ill = 0; ill < nell; ++ill) {
        Bl[ill] = 0;
        tcg_l[ill] = 0;
        txg_l[ill] = 0;
        T_l[ill] = 0;
    }

    FLOAT cbar = 0;  // sum_b W_b c_b
    FLOAT xbar = 0;  // sum_b W_b x_b
    FLOAT U = 0;     // general path only: sum_b W_b (s - c_b) / sigma_b^2

    if (sp.uniform) {
        int m = (int) floor((s - sp.c0) * sp.inv_ds + 0.5);

        if (m < 0) {
            m = 0;
        }
        else if (m >= sp.nbins) {
            m = sp.nbins - 1;
        }

        const FLOAT u = s - (sp.c0 + m * sp.ds);
        const FLOAT md = (2 * u - sp.ds) * sp.ds * sp.inv2sig2;
        const FLOAT rup = exp(md);
        const FLOAT rdn = (rup > 0) ? sp.iq / rup : exp(-md - sp.gg);
        const int kmax = sp.kmax;

        FLOAT sum = 1;
        FLOAT wu = 1, ru = rup;
        FLOAT wd = 1, rd = rdn;

        for (int t = 1; t <= kmax; ++t) {
            wu *= ru;
            ru *= sp.iq;
            wd *= rd;
            rd *= sp.iq;

            const bool oku = (m + t < sp.nbins) && (wu > sp.cutoff);
            const bool okd = (m - t >= 0) && (wd > sp.cutoff);

            if (oku) {
                sum += wu;
            }

            if (okd) {
                sum += wd;
            }

            if (!oku && !okd) {
                break;
            }
        }

        const FLOAT scale = 1 / sum;

#define CUCOUNT_SOFT_VJP_POLE_TAP_U(B, W)                                      \
        do {                                                                   \
            const FLOAT c_ = sp.c0 + (B) * sp.ds;                              \
            const FLOAT d_ = s - c_;                                           \
            const FLOAT x_ = d_ * d_ * sp.inv2sig2;                            \
            const FLOAT w_ = (W) * scale;                                      \
            const FLOAT *g_ = &g[(size_t) (B) * nell];                         \
            cbar += w_ * c_;                                                   \
            xbar += w_ * x_;                                                   \
                                                                               \
            for (int ill = 0; ill < nell; ++ill) {                             \
                Bl[ill] += w_ * g_[ill];                                       \
                tcg_l[ill] += w_ * g_[ill] * c_;                               \
                txg_l[ill] += w_ * g_[ill] * x_;                               \
            }                                                                  \
        } while (0)

        CUCOUNT_SOFT_VJP_POLE_TAP_U(m, 1);

        wu = 1; ru = rup;
        wd = 1; rd = rdn;

        for (int t = 1; t <= kmax; ++t) {
            wu *= ru;
            ru *= sp.iq;
            wd *= rd;
            rd *= sp.iq;

            const bool oku = (m + t < sp.nbins) && (wu > sp.cutoff);
            const bool okd = (m - t >= 0) && (wd > sp.cutoff);

            if (oku) {
                CUCOUNT_SOFT_VJP_POLE_TAP_U(m + t, wu);
            }

            if (okd) {
                CUCOUNT_SOFT_VJP_POLE_TAP_U(m - t, wd);
            }

            if (!oku && !okd) {
                break;
            }
        }

#undef CUCOUNT_SOFT_VJP_POLE_TAP_U
    }
    else {
        // Same window as the forward's soft_add_general, from the same helper.
        const FLOAT *cen = sp.centres;
        const FLOAT *i2s2 = sp.inv2s2;
        const bool fast = sp.fast_taps != 0;
        const SoftWindow win = soft_general_window(sp, s);
        const int m = win.m;

        FLOAT sum = 1;

        for (int k = 1; k <= win.up; ++k) {
            const FLOAT dd = s - cen[m + k];
            sum += soft_tap_weight(dd * dd * i2s2[m + k] - win.lmin, fast);
        }

        for (int k = 1; k <= win.dn; ++k) {
            const FLOAT dd = s - cen[m - k];
            sum += soft_tap_weight(dd * dd * i2s2[m - k] - win.lmin, fast);
        }

        const FLOAT scale = 1 / sum;

#define CUCOUNT_SOFT_VJP_POLE_TAP_G(B, W)                                      \
        do {                                                                   \
            const FLOAT c_ = cen[B];                                           \
            const FLOAT d_ = s - c_;                                           \
            const FLOAT i2_ = i2s2[B];                                         \
            const FLOAT x_ = d_ * d_ * i2_;                                    \
            const FLOAT w_ = (W) * scale;                                      \
            const FLOAT *g_ = &g[(size_t) (B) * nell];                         \
            cbar += w_ * c_;                                                   \
            xbar += w_ * x_;                                                   \
            U += w_ * (s - c_) * i2_;                                          \
                                                                               \
            for (int ill = 0; ill < nell; ++ill) {                             \
                Bl[ill] += w_ * g_[ill];                                       \
                tcg_l[ill] += w_ * g_[ill] * c_;                               \
                txg_l[ill] += w_ * g_[ill] * x_;                               \
                T_l[ill] += w_ * g_[ill] * (c_ - s) * i2_;                     \
            }                                                                  \
        } while (0)

        CUCOUNT_SOFT_VJP_POLE_TAP_G(m, 1);

        for (int k = 1; k <= win.up; ++k) {
            const FLOAT dd = s - cen[m + k];
            CUCOUNT_SOFT_VJP_POLE_TAP_G(
                m + k, soft_tap_weight(dd * dd * i2s2[m + k] - win.lmin, fast));
        }

        for (int k = 1; k <= win.dn; ++k) {
            const FLOAT dd = s - cen[m - k];
            CUCOUNT_SOFT_VJP_POLE_TAP_G(
                m - k, soft_tap_weight(dd * dd * i2s2[m - k] - win.lmin, fast));
        }

#undef CUCOUNT_SOFT_VJP_POLE_TAP_G
    }

    // Contract the per-multipole sums with the profile: this is where the mu
    // weights disappear from the s adjoint and reappear as dL/dmu.
    FLOAT A = 0;
    FLOAT tcg = 0;
    FLOAT txg = 0;
    FLOAT T = 0;

    for (int ill = 0; ill < nell; ++ill) {
        A += M[ill] * Bl[ill];
        tcg += M[ill] * tcg_l[ill];
        txg += M[ill] * txg_l[ill];
        T += M[ill] * T_l[ill];
        out->dmu += w * Bl[ill] * dM[ill];
    }

    out->dw = A;

    if (sp.uniform) {
        out->ds = w * (tcg - cbar * A) * 2 * sp.inv2sig2;
    }
    else {
        out->ds = 2 * w * (T + A * U);
    }
}


__device__ __forceinline__ void soft_vjp_pair(
    const FLOAT *g,
    const SoftBinSpec &sp,
    FLOAT s,
    FLOAT mu,
    FLOAT w,
    SoftVjpPair *out)
{
    if (sp.nell > 0) {
        soft_vjp_pair_pole(g, sp, s, mu, w, out);
    }
    else if (sp.uniform) {
        soft_vjp_pair_uniform(g, sp, s, w, out);
    }
    else {
        soft_vjp_pair_general(g, sp, s, w, out);
    }
}


// ============================================================================
// Adjoint op
// ============================================================================

struct Count2SoftVjpOp {
    const FLOAT *g;

    FLOAT *grad_position1;
    FLOAT *grad_position2;
    FLOAT *grad_weight1;
    FLOAT *grad_weight2;
    FLOAT *grad_sigma;

    // Slot -> input particle. The mesh reorders particles by cell, and the
    // gradients are per input particle, so the slot number cannot be used.
    const size_t *original_index1;
    const size_t *original_index2;
    const FLOAT *positions2;  // mesh2.positions, to recover the secondary slot

    size_t slot1;

    FLOAT *position1;
    FLOAT *sposition1;
    FLOAT *value1;

    IndexValue index_value1;
    IndexValue index_value2;

    WeightAttrs wattrs;
    SelectionAttrs sattrs;
    MeshAttrs mattrs;
    SoftBinSpec spec;

    __device__ inline void operator()(
        size_t jj,
        FLOAT *position2,
        FLOAT *sposition2,
        FLOAT *value2)
    {
        if (!is_selected_pair(
                sposition1,
                sposition2,
                position1,
                position2,
                sattrs,
                mattrs)) {
            return;
        }

        FLOAT diff[NDIM];
        difference(diff, position2, position1, mattrs);

        const FLOAT s = sqrt(dot(diff, diff));

        // The same pair weight as the forward, kept as factors because the
        // weight cotangents are its partial derivatives.
        FLOAT w1 = 1;
        FLOAT w2 = 1;
        FLOAT bw = 1;

        if (index_value1.size_individual_weight) {
            w1 = value1[index_value1.start_individual_weight];
        }

        if (index_value2.size_individual_weight) {
            w2 = value2[index_value2.start_individual_weight];
        }

        if (index_value1.size_bitwise_weight &&
            index_value2.size_bitwise_weight) {
            bw = pair_bitwise_weight(
                value1,
                value2,
                index_value1,
                index_value2,
                wattrs.bitwise);
        }

        FLOAT pair_weight = 1;

        if (index_value1.size_individual_weight) {
            pair_weight *= w1;
        }

        if (index_value2.size_individual_weight) {
            pair_weight *= w2;
        }

        if (index_value1.size_bitwise_weight &&
            index_value2.size_bitwise_weight) {
            pair_weight *= bw;
        }

        if (index_value1.size_negative_weight &&
            index_value2.size_negative_weight) {
            pair_weight -=
                value1[index_value1.start_negative_weight] *
                value2[index_value2.start_negative_weight];
        }

        // The pair's mu, measured exactly as the forward measures it.
        FLOAT mu = 0., mu2 = 0.;

        if (spec.nell > 0) {
            compute_pair_mu(diff, sposition1, sposition2, position1, position2,
                            spec.los, s, s * s, true, &mu, &mu2);
        }

        SoftVjpPair acc;
        soft_vjp_pair(g, spec, s, mu, pair_weight, &acc);

        const size_t i1 = original_index1[slot1];
        const size_t i2 = original_index2[(position2 - positions2) / NDIM];

        // d pair_weight / d w1 = w2 * bw, and the negative-weight term does not
        // depend on the individual weights.
        if (index_value1.size_individual_weight) {
            atomicAdd(&grad_weight1[i1], acc.dw * w2 * bw);
        }

        if (index_value2.size_individual_weight) {
            atomicAdd(&grad_weight2[i2], acc.dw * w1 * bw);
        }

        // s = |r1 - r2|, so ds/dr1 = (r1 - r2) / s = -diff / s. With soft mu
        // binning there is a second, mu-only direction: mu = (diff . lhat) / s,
        // so with rhat = diff / s and k the line of sight's own dependence on
        // that endpoint (zero for the fixed x/y/z axes),
        //
        //   dL/dr1_b = -ds rhat_b + dL/dmu [ -(lhat_b - mu rhat_b)/s
        //                                    + k1 (rhat_b - mu lhat_b) ]
        //   dL/dr2_b = +ds rhat_b + dL/dmu [ +(lhat_b - mu rhat_b)/s
        //                                    + k2 (rhat_b - mu lhat_b) ]
        //
        // (see soft_mu_line_of_sight for where k comes from).
        if (s > 0) {
            const FLOAT e = acc.ds / s;
            FLOAT *gp1 = &grad_position1[NDIM * i1];
            FLOAT *gp2 = &grad_position2[NDIM * i2];

            if (acc.dmu != 0) {
                FLOAT lhat[NDIM];
                FLOAT k1 = 0, k2 = 0;

                soft_mu_line_of_sight(spec.los, sposition1, sposition2,
                                      position1, position2, lhat, &k1, &k2);

                const FLOAT gm = acc.dmu;

                for (size_t axis = 0; axis < NDIM; ++axis) {
                    const FLOAT rhat = diff[axis] / s;
                    const FLOAT dl = (lhat[axis] - mu * rhat) / s;
                    const FLOAT dk = rhat - mu * lhat[axis];

                    atomicAdd(&gp1[axis], -e * diff[axis] + gm * (k1 * dk - dl));
                    atomicAdd(&gp2[axis], e * diff[axis] + gm * (k2 * dk + dl));
                }
            }
            else {
                for (size_t axis = 0; axis < NDIM; ++axis) {
                    atomicAdd(&gp1[axis], -e * diff[axis]);
                    atomicAdd(&gp2[axis], e * diff[axis]);
                }
            }
        }

        if (acc.dsigma != 0) {
            atomicAdd(grad_sigma, acc.dsigma);
        }
    }
};


// ============================================================================
// Adjoint kernel
// ============================================================================
//
// G_SHARED stages the cotangent in shared memory, since every pair in a cell
// gathers from it and a block-wide read-only copy is cheaper than L1 traffic.
// The accumulation itself is all global atomics: unlike the histogram, the
// gradient targets are per particle and cannot be privatized per block.
template <MESH_TYPE TARGET_MESH_TYPE, bool G_SHARED>
__global__ void count2_soft_vjp_kernel(
    const FLOAT *cotangent,
    FLOAT *grad_position1,
    FLOAT *grad_position2,
    FLOAT *grad_weight1,
    FLOAT *grad_weight2,
    FLOAT *grad_sigma,
    Mesh mesh1,
    Mesh mesh2,
    MeshAttrs mattrs,
    SelectionAttrs sattrs,
    WeightAttrs wattrs,
    SoftBinSpec spec)
{
    extern __shared__ FLOAT gsh[];

    const FLOAT *g = cotangent;

    if constexpr (G_SHARED) {
        for (int i = threadIdx.x; i < spec.nslots; i += blockDim.x) {
            gsh[i] = cotangent[i];
        }

        __syncthreads();
        g = gsh;
    }

    const size_t stride = gridDim.x * blockDim.x;
    const size_t gid = threadIdx.x + blockIdx.x * blockDim.x;

    for (size_t ii = gid; ii < mesh1.total_nparticles; ii += stride) {
        FLOAT *position1 = &(mesh1.positions[NDIM * ii]);
        FLOAT *sposition1 = &(mesh1.spositions[NDIM * ii]);
        FLOAT *value1 = &(mesh1.values[mesh1.index_value.size * ii]);

        Count2SoftVjpOp op{
            g,
            grad_position1,
            grad_position2,
            grad_weight1,
            grad_weight2,
            grad_sigma,
            mesh1.original_index,
            mesh2.original_index,
            mesh2.positions,
            ii,
            position1,
            sposition1,
            value1,
            mesh1.index_value,
            mesh2.index_value,
            wattrs,
            sattrs,
            mattrs,
            spec
        };

        for_each_candidate<TARGET_MESH_TYPE>(
            position1,
            sposition1,
            mesh2,
            mattrs,
            op);
    }
}


template <MESH_TYPE TARGET_MESH_TYPE, bool G_SHARED>
static void launch_soft_vjp(
    const FLOAT *cotangent,
    FLOAT *grad_position1,
    FLOAT *grad_position2,
    FLOAT *grad_weight1,
    FLOAT *grad_weight2,
    FLOAT *grad_sigma,
    const Mesh *list_mesh,
    const MeshAttrs &mattrs,
    const SelectionAttrs &sattrs,
    const WeightAttrs &wattrs,
    const SoftBinSpec &spec,
    int nblocks,
    int nthreads_per_block,
    size_t shmem,
    cudaStream_t stream)
{
    count2_soft_vjp_kernel<TARGET_MESH_TYPE, G_SHARED><<<
        nblocks,
        nthreads_per_block,
        shmem,
        stream>>>(
            cotangent,
            grad_position1,
            grad_position2,
            grad_weight1,
            grad_weight2,
            grad_sigma,
            list_mesh[0],
            list_mesh[1],
            mattrs,
            sattrs,
            wattrs,
            spec);
}


void count2_soft_vjp(
    const FLOAT *cotangent,
    FLOAT *grad_position1,
    FLOAT *grad_position2,
    FLOAT *grad_weight1,
    FLOAT *grad_weight2,
    FLOAT *grad_sigma,
    const Mesh *list_mesh,
    const Count2Attrs &attrs,
    const SoftBinSpec &spec_in,
    DeviceMemoryBuffer *buffer,
    cudaStream_t stream)
{
    // A local copy so the general path can point the spec at freshly uploaded
    // tables without mutating the caller's request.
    SoftBinSpec spec = spec_in;

    const MeshAttrs &mattrs = attrs.mattrs;
    const SelectionAttrs &sattrs = attrs.sattrs;
    const WeightAttrs &wattrs = attrs.wattrs;

    if (!list_mesh[0].original_index || !list_mesh[1].original_index) {
        log_message(LOG_LEVEL_ERROR,
                    "count2_soft_vjp needs meshes built with "
                    "keep_original_index = true.\n");
        return;
    }

    upload_soft_tables(spec, buffer, stream);

    int nblocks, nthreads_per_block;
    // The extra parentheses keep the comma in the template argument list from
    // splitting the macro's arguments.
    CONFIGURE_KERNEL_LAUNCH((count2_soft_vjp_kernel<MESH_CARTESIAN, true>),
                            nblocks, nthreads_per_block, buffer);

    int dev = 0;
    cudaGetDevice(&dev);
    int max_shmem = 48 * 1024;
    cudaDeviceGetAttribute(&max_shmem, cudaDevAttrMaxSharedMemoryPerBlock, dev);

    const size_t need = (size_t) spec.nslots * sizeof(FLOAT);
    const bool g_shared = need <= (size_t) max_shmem;
    const size_t shmem = g_shared ? need : 0;

#define CUCOUNT_LAUNCH_SOFT_VJP(MESH, SHARED)                               \
    launch_soft_vjp<MESH, SHARED>(                                          \
        cotangent, grad_position1, grad_position2, grad_weight1,            \
        grad_weight2, grad_sigma, list_mesh, mattrs, sattrs, wattrs, spec,  \
        nblocks, nthreads_per_block, shmem, stream)

    if (mattrs.type == MESH_ANGULAR) {
        if (g_shared) {
            CUCOUNT_LAUNCH_SOFT_VJP(MESH_ANGULAR, true);
        }
        else {
            CUCOUNT_LAUNCH_SOFT_VJP(MESH_ANGULAR, false);
        }
    }
    else {
        if (g_shared) {
            CUCOUNT_LAUNCH_SOFT_VJP(MESH_CARTESIAN, true);
        }
        else {
            CUCOUNT_LAUNCH_SOFT_VJP(MESH_CARTESIAN, false);
        }
    }

#undef CUCOUNT_LAUNCH_SOFT_VJP

    cudaError_t last_error = cudaPeekAtLastError();

    if (last_error != cudaSuccess) {
        log_message(LOG_LEVEL_ERROR, "count2_soft_vjp launch failed: %s\n",
                    cudaGetErrorString(last_error));
    }

    release_soft_tables(spec, buffer);
}
